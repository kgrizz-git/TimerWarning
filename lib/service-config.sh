#!/bin/bash

###############################################################################
# Sleep Warning System - Service Configuration Module
#
# This module handles systemd service configuration for different system modes
# (Desktop Mode vs Gaming Mode). It creates and manages drop-in files that
# configure environment variables and service dependencies based on the detected
# system mode.
#
# Dependencies: lib/display-detection.sh (for mode detection)
#
# Usage: Source this file to access service configuration functions
#   source lib/service-config.sh
#
# Enhancement: #4 - Systemd Service Environment Detection
###############################################################################

# Get the path to the systemd drop-in directory for sleep-warning.service
# Returns: Full path to ~/.config/systemd/user/sleep-warning.service.d/
get_service_dropin_path() {
    local dropin_dir="${HOME}/.config/systemd/user/sleep-warning.service.d"
    echo "${dropin_dir}"
}

# Create or update service drop-in file for a specific mode
# Parameters:
#   $1: System mode ("desktop" or "gaming")
#   $2: Display identifier (optional, will be auto-detected if not provided)
# Returns: 0 on success, 1 on error
# Side effects: Creates/updates drop-in file and removes old mode-specific files
create_service_dropin() {
    local mode="$1"
    local display_id="$2"
    local dropin_dir
    dropin_dir=$(get_service_dropin_path)
    local dropin_file="${dropin_dir}/mode-${mode}.conf"
    
    # Validate mode
    if [ "${mode}" != "desktop" ] && [ "${mode}" != "gaming" ]; then
        echo "Error: Invalid mode '${mode}'. Must be 'desktop' or 'gaming'." >&2
        return 1
    fi
    
    # Create drop-in directory if it doesn't exist
    if [ ! -d "${dropin_dir}" ]; then
        if ! mkdir -p "${dropin_dir}"; then
            echo "Error: Failed to create drop-in directory: ${dropin_dir}" >&2
            return 1
        fi
    fi
    
    # Auto-detect display identifier if not provided
    if [ -z "${display_id}" ]; then
        # Source display-detection.sh if not already sourced
        if ! type get_mode_display_identifier >/dev/null 2>&1; then
            local script_dir
            script_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
            if [ -f "${script_dir}/display-detection.sh" ]; then
                source "${script_dir}/display-detection.sh"
            else
                echo "Error: Cannot find display-detection.sh" >&2
                return 1
            fi
        fi
        
        display_id=$(get_mode_display_identifier "${mode}")
        if [ "${display_id}" = "unknown" ]; then
            echo "Warning: Could not determine display identifier for mode '${mode}', using defaults" >&2
            # Use defaults
            if [ "${mode}" = "desktop" ]; then
                display_id=":0"
            else
                display_id="wayland-0"
            fi
        fi
    fi
    
    # Remove old mode-specific drop-in files (cleanup)
    local old_file
    for old_file in "${dropin_dir}"/mode-desktop.conf "${dropin_dir}"/mode-gaming.conf; do
        if [ -f "${old_file}" ] && [ "${old_file}" != "${dropin_file}" ]; then
            rm -f "${old_file}"
        fi
    done
    
    # Generate drop-in file content
    local dropin_content=""
    case "${mode}" in
        desktop)
            # Desktop Mode: Set DISPLAY environment variable
            dropin_content="[Service]
# Mode-specific configuration for Desktop Mode (X11/KDE Plasma)
# This file is automatically generated by the installation/configuration scripts.
# To reconfigure, run: sleep-warning-configure
Environment=DISPLAY=${display_id}
"
            ;;
        gaming)
            # Gaming Mode: Set WAYLAND_DISPLAY and GAMESCOPE_SESSION
            dropin_content="[Service]
# Mode-specific configuration for Gaming Mode (Wayland/gamescope)
# This file is automatically generated by the installation/configuration scripts.
# To reconfigure, run: sleep-warning-configure
Environment=WAYLAND_DISPLAY=${display_id}
Environment=GAMESCOPE_SESSION=1
"
            ;;
    esac
    
    # Write drop-in file
    if echo "${dropin_content}" > "${dropin_file}"; then
        return 0
    else
        echo "Error: Failed to write drop-in file: ${dropin_file}" >&2
        return 1
    fi
}

# Remove service drop-in files
# Parameters:
#   $1: Mode to remove ("desktop", "gaming", or "all" to remove all)
# Returns: 0 on success, 1 on error
remove_service_dropin() {
    local mode="${1:-all}"
    local dropin_dir
    dropin_dir=$(get_service_dropin_path)
    
    case "${mode}" in
        desktop|gaming)
            local dropin_file="${dropin_dir}/mode-${mode}.conf"
            if [ -f "${dropin_file}" ]; then
                if rm -f "${dropin_file}"; then
                    return 0
                else
                    echo "Error: Failed to remove drop-in file: ${dropin_file}" >&2
                    return 1
                fi
            fi
            # File doesn't exist, consider it success
            return 0
            ;;
        all)
            # Remove all mode-specific drop-in files
            local removed=false
            local dropin_file
            for dropin_file in "${dropin_dir}"/mode-desktop.conf "${dropin_dir}"/mode-gaming.conf; do
                if [ -f "${dropin_file}" ]; then
                    if rm -f "${dropin_file}"; then
                        removed=true
                    else
                        echo "Warning: Failed to remove drop-in file: ${dropin_file}" >&2
                    fi
                fi
            done
            return 0
            ;;
        *)
            echo "Error: Invalid mode '${mode}'. Must be 'desktop', 'gaming', or 'all'." >&2
            return 1
            ;;
    esac
}

# Configure service for detected system mode
# Parameters:
#   $1: System mode ("desktop" or "gaming", optional - will auto-detect if not provided)
#   $2: Display identifier (optional, will be auto-detected if not provided)
# Returns: 0 on success, 1 on error
# Side effects: Creates drop-in file and reloads systemd daemon
configure_service_for_mode() {
    local mode="$1"
    local display_id="$2"
    
    # Auto-detect mode if not provided
    if [ -z "${mode}" ]; then
        # Source display-detection.sh if not already sourced
        if ! type detect_system_mode >/dev/null 2>&1; then
            local script_dir
            script_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
            if [ -f "${script_dir}/display-detection.sh" ]; then
                source "${script_dir}/display-detection.sh"
            else
                echo "Error: Cannot find display-detection.sh" >&2
                return 1
            fi
        fi
        
        mode=$(detect_system_mode)
        if [ "${mode}" = "unknown" ]; then
            echo "Warning: Could not detect system mode, skipping service configuration" >&2
            return 1
        fi
    fi
    
    # Validate mode
    if [ "${mode}" != "desktop" ] && [ "${mode}" != "gaming" ]; then
        echo "Error: Invalid mode '${mode}'. Must be 'desktop' or 'gaming'." >&2
        return 1
    fi
    
    # Create drop-in file
    if ! create_service_dropin "${mode}" "${display_id}"; then
        return 1
    fi
    
    # Reload systemd daemon to pick up changes
    if command -v systemctl >/dev/null 2>&1; then
        if systemctl --user daemon-reload >/dev/null 2>&1; then
            return 0
        else
            echo "Warning: Failed to reload systemd daemon, but drop-in file was created" >&2
            return 0  # Still consider it success since file was created
        fi
    else
        echo "Warning: systemctl not found, cannot reload systemd daemon" >&2
        return 0  # Still consider it success since file was created
    fi
}

# Get current service configuration mode
# Returns: "desktop", "gaming", or "none" (if no drop-in file exists)
get_current_service_mode() {
    local dropin_dir
    dropin_dir=$(get_service_dropin_path)
    
    if [ -f "${dropin_dir}/mode-desktop.conf" ]; then
        echo "desktop"
        return 0
    elif [ -f "${dropin_dir}/mode-gaming.conf" ]; then
        echo "gaming"
        return 0
    else
        echo "none"
        return 0
    fi
}
